package com.github.lorenj.wordtint.enums;


/**
 * 英语单词结构
 *
 * @author cnsukidayo
 * @date 2023/11/4 12:58
 */
public enum WordStructure {

    /**
     * 单词原文
     */
    WORD_ORIGIN,
    /**
     * 美式音标
     */
    US_PHONETIC,
    /**
     * 英式音标
     */
    UK_PHONETIC,
    /**
     * 形容词
     */
    ADJ,
    /**
     * 副词
     */
    ADV,
    /**
     * 动词
     */
    V,
    /**
     * 不及物动词
     */
    VI,
    /**
     * 及物动词
     */
    VT,
    /**
     * 名词
     */
    N,
    /**
     * 连词
     */
    CONJ,
    /**
     * 代词
     */
    PRON,
    /**
     * 数次
     */
    NUM,
    /**
     * 冠词
     */
    ART,
    /**
     * 介词
     */
    PREP,
    /**
     * 感叹词
     */
    INT,
    /**
     * 助动词
     */
    AUX,
    /**
     * 扩展
     */
    EXPAND,
    /**
     * 介词短语
     */
    PHRASE,
    /**
     * 例句
     */
    SENTENCE;
}
